ALTER TABLE users ADD COLUMN session_version INT NOT NULL DEFAULT 0, ALTER COLUMN role SET DEFAULT 'viewer';
CREATE TABLE user_entity_grants (
  user_id INT NOT NULL, entity_id INT NOT NULL, PRIMARY KEY(user_id, entity_id),
  FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  FOREIGN KEY(entity_id) REFERENCES wecom_entities(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;
CREATE TABLE role_policies (role VARCHAR(32) PRIMARY KEY, permissions JSON NOT NULL) ENGINE=InnoDB;
CREATE TABLE security_events (
  id INT AUTO_INCREMENT PRIMARY KEY, actor INT NOT NULL, action VARCHAR(64) NOT NULL,
  target VARCHAR(80) NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX(created_at)
) ENGINE=InnoDB;
